"""CASIO character table (FONTCHARACTER) lookups.

The table lives in ``data/charmap.json`` and is generated by
``tools/extract_charmap.py`` from a G2E file that EactMaker produced for every
palette symbol.  Each entry maps a byte sequence (1 byte, or 2 bytes starting
with a lead byte) to:

* ``eam``      -- the canonical spelling in EactMaker markup (``Α``, ``\\i;``, ``_a``)
* ``aliases``  -- other spellings EactMaker accepts for the same bytes
* ``unicode``  -- Unicode characters that should encode to these bytes
* ``preview``  -- a Unicode look-alike used by the text preview
* ``name`` / ``category`` -- documentation
"""
from __future__ import annotations

import json
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from importlib import resources


@dataclass(frozen=True)
class Symbol:
    code: bytes
    eam: str
    aliases: tuple[str, ...]
    unicode: tuple[str, ...]
    preview: str
    name: str
    category: str


class CharMap:
    def __init__(self, data: dict):
        self.lead_bytes = frozenset(int(b, 16) for b in data["lead_bytes"])
        self.symbols: list[Symbol] = []
        self.by_code: dict[bytes, Symbol] = {}
        self.by_unicode: dict[str, Symbol] = {}
        self.by_eam: dict[str, Symbol] = {}
        for e in data["entries"]:
            sym = Symbol(bytes.fromhex(e["bytes"]), e["eam"], tuple(e["aliases"]),
                         tuple(e["unicode"]), e["preview"], e["name"], e["category"])
            self.symbols.append(sym)
            self.by_code.setdefault(sym.code, sym)
            for u in sym.unicode:
                self.by_unicode.setdefault(u, sym)
            for spelling in (sym.eam, *sym.aliases):
                self.by_eam.setdefault(spelling, sym)

    # -- encoding -----------------------------------------------------------
    def encode_char(self, ch: str) -> bytes | None:
        """Bytes for one Unicode character, or None if CASIO has no such glyph."""
        sym = self.by_unicode.get(ch)
        return sym.code if sym else None

    def subscript(self, ch: str) -> bytes | None:
        """Bytes of the subscript glyph for ``ch`` (letters, digits, + and -)."""
        if ch.isascii() and ch.isalpha():
            sym = self.by_eam.get("_" + ch)
            return sym.code if sym else None
        sub = {"+": "₊", "-": "₋", "−": "₋"}.get(ch)
        if ch.isascii() and ch.isdigit():
            sub = "₀₁₂₃₄₅₆₇₈₉"[int(ch)]
        if sub:
            return self.by_unicode[sub].code
        return None

    def func(self, name: str) -> Symbol | None:
        """Look up a ``\\name;`` palette command."""
        return self.by_eam.get("\\" + name + ";")

    def fallback(self, ch: str) -> tuple[bytes, str] | None:
        """Best-effort replacement for a character with no CASIO glyph.

        Returns (bytes, replacement_text) when the character decomposes into
        something that exists (for example 'ǵ' -> 'g'), else None.
        """
        base = "".join(c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))
        if base and base != ch and all(c in self.by_unicode for c in base):
            return b"".join(self.by_unicode[c].code for c in base), base
        return None

    # -- decoding -----------------------------------------------------------
    def split(self, data: bytes) -> list[bytes]:
        """Split raw bytes into character codes (1 byte, or lead byte + 1)."""
        out, i = [], 0
        while i < len(data):
            n = 2 if data[i] in self.lead_bytes and i + 1 < len(data) else 1
            out.append(data[i:i + n])
            i += n
        return out

    def lookup(self, code: bytes) -> Symbol | None:
        return self.by_code.get(code)


@lru_cache(maxsize=1)
def default() -> CharMap:
    """The table shipped with the package."""
    text = resources.files("eact").joinpath("data/charmap.json").read_text(encoding="utf-8")
    return CharMap(json.loads(text))
