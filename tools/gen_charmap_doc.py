#!/usr/bin/env python3
"""Write docs/CHARMAP.md from src/eact/data/charmap.json.

    python3 tools/gen_charmap_doc.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "src/eact/data/charmap.json").read_text(encoding="utf-8"))

TITLES = {
    "ascii": "ASCII", "math": "Math symbols", "misc": "Miscellaneous", "subscript": "Subscripts",
    "greek": "Greek", "latin": "Latin accented letters", "cyrillic": "Cyrillic", "escape": "Escapes",
}


def code(s: str) -> str:
    s = s.replace("|", "\\|")
    return f"`` {s} ``" if "`" in s else f"`{s}`"


def cell(s: str) -> str:
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("`", "\\`") if s else ""


out = [
    "# CASIO character table",
    "",
    "Generated by `tools/gen_charmap_doc.py` from `src/eact/data/charmap.json`, which",
    "`tools/extract_charmap.py` derives from EactMaker output (see",
    "[REVERSE_ENGINEERING_LOG.md](REVERSE_ENGINEERING_LOG.md)). **Do not edit by hand.**",
    "",
    "Columns:",
    "* **Bytes**: what is stored in the .g2e file. Two-byte codes start with a",
    "  lead byte: `7F`, `E5`, `E6`, `E7` (`F7`, `F9` are also lead bytes on the calculator).",
    "* **EactMaker markup**: how to write it in `.eam` markup.",
    "* **Unicode input**: characters that `eact` converts to these bytes, in LaTeX text or in `.eam`.",
    "* **Name**: a description.",
    "",
    f"{len(data['entries'])} symbols in total.",
    "",
]
for cat, title in TITLES.items():
    rows = [e for e in data["entries"] if e["category"] == cat]
    if not rows:
        continue
    out += [f"## {title}", "", "| Bytes | EactMaker markup | Unicode input | Name |", "|---|---|---|---|"]
    for e in rows:
        out.append(f"| `{e['bytes'].upper()}` | {code(e['eam'])} | {cell(' '.join(e['unicode']))} | {cell(e['name'])} |")
    out.append("")

(ROOT / "docs" / "CHARMAP.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/CHARMAP.md")
